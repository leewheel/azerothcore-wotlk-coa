-- By leewheel 2026年11月9日
-- 机器人按名字找 BOSS 的英文别名表。
--
-- 背景：mod-playerbots 用 AI_VALUE2(Unit*, "find target", "illidan stormrage") 这类调用在 1221 处
-- 按英文名识别 BOSS 与机制怪，底层走 CoaNameIs(unit->GetName(), CoaNameKey(名字))。
-- 而 CoaNameKey 只做大小写与弯引号归一，不认中文：一旦把 creature_template.name 汉化，
-- 这 1221 处会全部匹配不上，机器人副本/团队机制整片失效。
--
-- 本表把「调用点写的英文名」固化成 entry 列表（键为小写，entries 为逗号分隔的 entry），
-- 模块在 FindTargetValue 里先按名字匹配，匹配不上再查本表按 entry 匹配。
-- 这样无论 creature_template.name 是英文还是中文，机器人认 BOSS 都不受影响。
-- 数据来源：从模块源码抽出 268 个 find target 名字，在 3395 上按当时仍是英文的
-- creature_template.name 逐个解析成 entry；garfrost 手工补为 Forgemaster Garfrost。
-- End By leewheel

CREATE TABLE IF NOT EXISTS `coa_bot_target_alias` (
  `name` VARCHAR(128) NOT NULL COMMENT '调用点写的英文名，全小写',
  `entries` VARCHAR(255) NOT NULL COMMENT '逗号分隔的 creature_template.entry',
  PRIMARY KEY (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='机器人按名字找 BOSS 的英文名到 entry 别名表';

